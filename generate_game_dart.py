"""Derive the matched Dart kernels from this suite's restricted ArkTS syntax.

This is intentionally not a general language translator. Only declarations,
typed buffers, constructors, list append, and the clock/floor adapters differ.
The checked-in generated Dart remains readable and is analyzed/compiled normally.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent

def dart_type(value):
    if value.startswith('FixedArray<'):
        return 'List<' + dart_type(value[11:-1]) + '>'
    if value.endswith('[]'):
        return 'List<' + dart_type(value[:-2]) + '>'
    return {'number': 'double', 'long': 'int', 'boolean': 'bool', 'string': 'String',
            'Float64Array': 'Float64List', 'Int32Array': 'Int32List'}.get(value, value)

def params(value):
    return ', '.join(dart_type(part.split(':')[1].strip()) + ' ' + part.split(':')[0].strip()
                     for part in value.split(',') if part.strip())

text = (ROOT / 'bench/game.ets').read_text()
text = re.sub(r'^interface GameWorld.*$', 'abstract interface class GameWorld { double tick(); }', text, flags=re.M)
text = re.sub(r'^function (floorInt|readInt|nowStamp|stampMs)\(.*\n', '', text, flags=re.M)
current_class = ''
lines = []
for line in text.splitlines():
    match = re.match(r'class (\w+)', line)
    if match:
        current_class = match[1]
    match = re.match(r'  constructor\(([^)]*)\) \{', line)
    if match:
        line = f'  {current_class}({params(match[1])}) {{'
    else:
        match = re.match(r'(\s*)(?:function |override )?(\w+)\(([^)]*)\): ([\w\[\]]+) \{(.*)', line)
        if match:
            line = f'{match[1]}{dart_type(match[4])} {match[2]}({params(match[3])}) {{{match[5]}'
    line = re.sub(r'^(  )(\w+): ([\w\[\]]+)( = )',
                  lambda m: m[1] + dart_type(m[3]) + ' ' + m[2] + m[4], line)
    def local(match):
        modifier, name, kind = match.groups()
        if kind:
            return ('final ' if modifier == 'const' else '') + dart_type(kind) + ' ' + name
        return ('final ' if modifier == 'const' else 'var ') + name
    line = re.sub(r'\b(const|let)\s+(\w+)(?:\s*:\s*([\w\[\]]+))?', local, line)
    line = re.sub(r'\bnew ', '', line)
    line = line.replace('Float64Array(', 'Float64List(').replace('Int32Array(', 'Int32List(')
    line = line.replace('.push(', '.add(').replace('console.log(', 'print(')
    lines.append(line)
prefix = """// Generated by generate_game_dart.py from bench/game.ets.
import 'dart:typed_data';
final _clock = Stopwatch()..start();
int floorInt(double value) => value.floor();
int readInt(Int32List values, int index) => values[index];
int nowStamp() => _clock.elapsedTicks;
double stampMs(int delta) => delta * 1000.0 / _clock.frequency;
"""
(ROOT / 'bench/game.dart').write_text(prefix + '\n'.join(lines) + '\n')
